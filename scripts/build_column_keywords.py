# 지역을 붙이는 비율 — 전부 붙이면 양산형이 된다
REGION_EVERY = 2


def _region_every(schemes):
    """제도가 하나뿐인 사이트(도산레이)는 제도 축이 안 펼쳐져 공급이 1/5로 준다.
    전국 사이트라 "경기도에서는 어느 법원" 같은 질문이 실제로 성립하므로
    그쪽은 지역을 촘촘히 붙인다 — 양산형 부풀리기가 아니라 의미 있는 축이다."""
    return 1 if len(schemes) == 1 else REGION_EVERY


def build(region, schemes, areas):
    """(분류, 키워드, 제도, 지역, 검색의도) 목록."""
    every = _region_every(schemes)
    rows, n = [], 0
    for scheme_name in schemes:
        for cat, tpl, intent in TOPICS:
            kw = tpl.format(s=scheme_name)
            rows.append((cat, kw, scheme_name, "", intent))
            n += 1
            # 3개마다 하나씩만 지역을 붙인다
            if n % every == 0 and areas:
                area = areas[(n // every - 1) % len(areas)]
                rows.append((cat, "%s %s" % (area, kw), scheme_name, area, intent))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()

    from app import create_app
    from app.config import REGION
    from app.keyword_rules import SCHEMES
    from app.models import Dong, Gu

    app = create_app()
    with app.app_context():
        # 지역 축: 구(또는 시도) + 동. 동이 많으면 일부만.
        areas = [g.name for g in Gu.query.order_by(Gu.sort).all()]
        areas += [d.name for d in Dong.query.order_by(Dong.sort).all()]

    schemes = [SCHEMES[c] for c in REGION["kw_schemes"]]
    rows = build(REGION["name"], schemes, areas)

    print("지역 %s / 제도 %s" % (REGION["name"], ", ".join(schemes)))
    print("주제 %d종 × 제도 %d = %d개 + 지역 변형 → **총 %d개**"
          % (len(TOPICS), len(schemes), len(TOPICS) * len(schemes), len(rows)))
    # 사이트당 하루 2편(5개 사이트 합계 10편) — 같은 사업자 도메인이 여럿이라
    # 합계로 보면 적지 않고, 공급이 1년 넘게 버틴다.
    print("하루 2편 기준 %d일치 (약 %.1f개월)\n"
          % (len(rows) // 2, len(rows) / 2 / 30))
    import collections
    c = collections.Counter(r[0] for r in rows)
    for k, v in c.most_common():
        print("   %-8s %4d" % (k, v))

    print("\n── 샘플 12개 ──")
    for r in rows[:6] + rows[len(rows) // 2:len(rows) // 2 + 6]:
        print("   [%s] %s" % (r[0], r[1]))

    if args.write:
        OUT.parent.mkdir(exist_ok=True)
