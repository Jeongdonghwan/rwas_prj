GENERIC_CORRECTION = (
    "이 용어는 {other}에서 쓰는 표현이라 {name} 절차에는 그대로 적용되지 않습니다. "
    "제도마다 절차와 용어가 다르므로, 본인 상황에 어느 제도가 맞는지부터 확인하는 편이 빠릅니다."
)


def correction_html(terms, scheme):
    """교정 문단 HTML. terms는 keyword_rules.correction_terms()의 결과."""
    if not terms or scheme == "rehab":
        return ""
    name = SCHEME_FACTS[scheme]["name"]
    seen, out = set(), []
    for t in terms:
        if t in seen:
            continue
        seen.add(t)
        text = CORRECTIONS.get(t, {}).get(scheme)
        if not text:
            text = GENERIC_CORRECTION.format(other="개인회생", name=name)
        out.append(text)
    body = " ".join(out)
    return (
        '<div class="kw-fix"><p><b>먼저 짚고 갑니다.</b> %s</p>'
        '<p class="kw-fix-cta">본인 상황에 맞는 제도가 무엇인지는 소득·재산·채무 구성을 '
        '함께 보고 판단합니다. 전화 상담으로 확인하실 수 있습니다.</p></div>' % body
    )
